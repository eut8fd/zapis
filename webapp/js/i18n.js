export function plural(n, forms) {
  if (cur === 'ru') return forms[ruIndex(n)];
  const set = FORMS[forms.join('|')];
  if (!set || !set[cur]) return forms[ruIndex(n)];
  const f = set[cur];
  return f.length === 1 ? f[0] : f[Math.abs(n) === 1 ? 0 : 1];
}


export const WD_FULL = CAL.ru.wdFull.slice();

const refill = (arr, src) => { arr.length = 0; src.forEach(x => arr.push(x)); };

export const locale = () => CAL[cur].locale;
/** Переключить язык. Возвращает true, если он действительно поменялся. */
export function applyLang(id) {
  const next = isLang(id) ? id : 'ru';
  const changed = next !== cur;
  cur = next;
  const c = CAL[cur];
  refill(MONTHS, c.months);
  refill(MON_SHORT, c.monShort);
  refill(MONTH_NAMES, c.monthNames);
  refill(WD, c.wd);
  refill(WD_FULL, c.wdFull);
  try { document.documentElement.lang = cur; } catch (e) { }
  return changed;
}
/* ---------------- Множественные формы ----------------
   В русском три формы, в английском две, в казахском числительное
   не меняет слово вовсе: «3 салон», а не «3 салона». Поэтому
   переводим не отдельное слово, а весь набор форм целиком.
------------------------------------------------------- */
const ruIndex = n => {
  const a = Math.abs(n) % 100, b = a % 10;
  if (a > 10 && a < 20) return 2;
  if (b > 1 && b < 5) return 1;
  if (b === 1) return 0;
  return 2;
};


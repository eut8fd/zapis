/**
 * Перевести строку. Ключ — русский оригинал; нет перевода — вернём его же.
 * Подстановки в фигурных скобках: t('Все {n}', { n: 12 }).
 */
export function t(ru, vars) {
  const table = DICT[cur];
  let out = (table && table[ru]) || ru;
  if (vars) {
    for (const k in vars) out = out.split('{' + k + '}').join(vars[k]);
  }
  return out;
}

